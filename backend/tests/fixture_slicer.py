"""Test-only fixture slicer.

Production slicing uses the Orca Slicer CLI (SYS-11). Tests need G-code for any
STL dropped into ``backend/tests/stl`` without requiring a slicer install, so
this module emits a small but grammar-faithful Orca-style G-code file from an
STL's bounding box: header/executable blocks, ``;LAYER_CHANGE`` + ``;Z:`` per
layer, skirt on layer 0, two wall loops, zig-zag infill, machine end G-code,
and filament/time trailer comments. It is fixture scaffolding only -- never
used by the production pipeline.
"""

from __future__ import annotations

import math
from pathlib import Path

from backend.batching.stl import load_stl

LAYER_HEIGHT = 0.2
SKIRT_MARGIN = 3.0
WALLS = 2
WALL_WIDTH = 0.45


def _fmt(v: float) -> str:
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return s if s else "0"


def _ring(lines: list[str], pts: list[tuple[float, float]], e_per_mm: float, filament: list[float], feed: float = 1500.0) -> None:
    lines.append(f"G1 F{feed:.0f}")
    for i, (x, y) in enumerate(pts):
        if i == 0:
            lines.append(f"G1 X{_fmt(x)} Y{_fmt(y)}")
            continue
        px, py = pts[i - 1]
        dist = math.hypot(x - px, y - py)
        filament[0] += dist * e_per_mm
        lines.append(f"G1 X{_fmt(x)} Y{_fmt(y)} E{dist * e_per_mm:.5f}")


def generate_gcode(stl_path: str | Path, layer_height: float = LAYER_HEIGHT) -> str:
    """Generate deterministic Orca-style G-code for an STL's bounding box."""

    mesh = load_stl(stl_path)
    (min_x, min_y, _), (max_x, max_y, _) = mesh.bounding_box
    depth = mesh.dimensions[2]
    n_layers = max(1, round(depth / layer_height))

    lines: list[str] = [
        "; HEADER_BLOCK_START",
        f"; generated by PrintHive fixture slicer for {Path(stl_path).name}",
        f"; total layer number: {n_layers}",
        "; HEADER_BLOCK_END",
        "",
        "; EXECUTABLE_BLOCK_START",
        "G90",
        "G21",
        "M83",
        "G28",
        "G92 E0",
        "M104 S200",
        "M140 S60",
        "M106 S0",
    ]
    filament = [0.0]
    e_per_mm = 0.05

    for k in range(n_layers):
        z = layer_height * (k + 1)
        lines += [";LAYER_CHANGE", f";Z:{z}", "G92 E0", ""]
        lines.append("G1 E-.8 F1800")
        lines.append(f"G1 X{_fmt(min_x)} Y{_fmt(min_y)} F7200")
        lines.append("G1 Z.6")
        lines.append(f"G1 Z{z}")
        lines.append("G1 E.8 F1800")

        if k == 0:
            s = SKIRT_MARGIN
            lines += [";TYPE:Skirt", ";WIDTH:0.45"]
            _ring(
                lines,
                [
                    (min_x - s, min_y - s),
                    (max_x + s, min_y - s),
                    (max_x + s, max_y + s),
                    (min_x - s, max_y + s),
                    (min_x - s, min_y - s),
                ],
                e_per_mm,
                filament,
            )

        for wall in range(WALLS):
            inset = wall * WALL_WIDTH
            x0, y0 = min_x + inset, min_y + inset
            x1, y1 = max_x - inset, max_y - inset
            if x1 <= x0 or y1 <= y0:
                break
            lines.append(f";TYPE:Wall-{wall}")
            _ring(lines, [(x0, y0), (x1, y0), (x1, y1), (x0, y1), (x0, y0)], e_per_mm, filament)

        lines.append(";TYPE:Infill")
        step = 4.0
        y = min_y + WALLS * WALL_WIDTH
        while y < max_y - WALLS * WALL_WIDTH:
            lines.append(f"G1 X{_fmt(min_x + WALLS * WALL_WIDTH)} Y{_fmt(y)}")
            x_end = max_x - WALLS * WALL_WIDTH
            dist = x_end - (min_x + WALLS * WALL_WIDTH)
            filament[0] += dist * e_per_mm
            lines.append(f"G1 X{_fmt(x_end)} Y{_fmt(y)} E{dist * e_per_mm:.5f}")
            y += step

    lines += [
        "; stop printing object",
        "G1 E-.8 F1800",
        "M106 S0",
        "M104 S0",
        "G28 X0",
        "M84",
        "; EXECUTABLE_BLOCK_END",
        "",
        f"; filament used [mm] = {filament[0]:.2f}",
    ]
    duration_s = n_layers * 12.5
    lines.append(
        f"; estimated printing time (normal mode) = {int(duration_s // 60)}m {int(duration_s % 60)}s"
    )
    lines.append("")
    return "\n".join(lines)


def fixture_slice_stl(stl_path: str | Path, output_dir: str | Path) -> Path:
    """Slice-protocol callable: (stl_path, output_dir) -> G-code path."""

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    out = output_dir / (Path(stl_path).stem + ".gcode")
    out.write_text(generate_gcode(stl_path))
    return out
