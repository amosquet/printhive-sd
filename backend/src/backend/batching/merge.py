"""G-code merging for design D-02 (Slice-Once G-code Merging).

The merger takes several cached per-job G-code files plus their packed plate
offsets and emits one dispatchable G-code file:

- one shared start sequence (per-file start blocks are stripped),
- layer-by-layer interleaving (all parts' layer at Z before any higher Z),
- X/Y translation by each part's packed offset,
- travel moves plus ``M486`` object tags between parts for per-object
  cancellation (FR-15 recovery),
- one shared end sequence.

Batching requires identical layer grids: parts whose ``;Z:`` sequences differ
cannot be interleaved and are rejected by :func:`merge_parts`.
"""

from __future__ import annotations

from dataclasses import dataclass

from .gcode import ParsedGcode, first_xy, first_xy_index, parse_gcode, translate_layer

_Z_KEY_EPS = 1e-6


class IncompatibleLayersError(ValueError):
    """Raised when parts in a batch do not share the same layer grid."""


@dataclass
class PlacedPart:
    """A parsed job plus its packed offset and rotation on the plate."""

    index: int  # M486 object id
    name: str
    parsed: ParsedGcode
    dx: float
    dy: float
    rotated: bool = False


def load_part(
    index: int, name: str, gcode_text: str, dx: float, dy: float, *, rotated: bool = False
) -> PlacedPart:
    return PlacedPart(
        index=index,
        name=name,
        parsed=parse_gcode(gcode_text, source=name),
        dx=dx,
        dy=dy,
        rotated=rotated,
    )


def _layer_grid(layers_zs: list[list[float]]) -> list[float]:
    """Layer Z grid shared by all parts.

    Batching requires identical layer *heights* (same profile), so every part's
    Z sequence must agree on the common prefix; parts may simply have fewer
    layers (shorter prints). The returned grid is the longest sequence.
    """

    grid = max(layers_zs, key=len)
    for zs in layers_zs:
        common = min(len(grid), len(zs))
        if any(abs(grid[i] - zs[i]) > _Z_KEY_EPS for i in range(common)):
            raise IncompatibleLayersError(
                "parts have different layer heights; batching requires the same "
                "profile (identical layer grid). Layer counts: "
                + ", ".join(str(len(z)) for z in layers_zs)
            )
    return grid


def merge_parts(
    parts: list[PlacedPart],
    travel_feedrate: float = 7200.0,
    header_lines: list[str] | None = None,
) -> str:
    """Merge placed parts into a single dispatchable G-code file."""

    if not parts:
        raise ValueError("no parts to merge")
    grid = _layer_grid([p.parsed.layer_heights for p in parts])

    out: list[str] = []
    if header_lines is None:
        header_lines = [
            "; HEADER_BLOCK_START",
            "; generated by PrintHive batching (slice-once G-code merging)",
            f"; parts in batch: {len(parts)}",
            "; " + ", ".join(f"{p.name}@({p.dx:.3f},{p.dy:.3f})" for p in parts),
            "; HEADER_BLOCK_END",
        ]
    out.extend(header_lines)
    out.append("")
    out.append("; EXECUTABLE_BLOCK_START")

    start_lines = parts[0].parsed.start_lines
    out.extend(start_lines)
    out.append(f"M486 T{len(parts)} ; total printable objects on this plate")
    out.append("")

    for z in grid:
        for part in parts:
            layer = next((l for l in part.parsed.layers if abs(l.z - z) <= _Z_KEY_EPS), None)
            if layer is None:
                continue
            translated = translate_layer(
                layer,
                part.dx,
                part.dy,
                rotated=part.rotated,
                footprint=part.parsed.footprint,
            )
            target = first_xy(translated)
            split_idx = first_xy_index(translated)
            if split_idx is None:
                split_idx = len(translated)
            out.extend(translated[:split_idx])
            out.append(f"M486 S{part.index} ; {part.name}")
            if target is not None:
                out.append(f"G1 X{target[0]:.3f} Y{target[1]:.3f} F{travel_feedrate:.0f} ; travel to {part.name}")
            out.extend(translated[split_idx:])
        out.append("")

    out.extend(parts[0].parsed.end_lines)
    out.append("; EXECUTABLE_BLOCK_END")

    total_filament = sum(p.parsed.filament_mm or 0.0 for p in parts)
    total_time = sum(p.parsed.duration_s or 0.0 for p in parts)
    out.append("")
    out.append(f"; total filament used [mm] = {total_filament:.2f}")
    hours = int(total_time // 3600)
    minutes = int((total_time % 3600) // 60)
    seconds = int(total_time % 60)
    out.append(
        f"; estimated printing time (normal mode) = {hours}h {minutes}m {seconds}s"
    )
    out.append("")
    return "\n".join(out)
